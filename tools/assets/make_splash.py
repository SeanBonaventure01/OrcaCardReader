#!/usr/bin/env python3
"""Builds the idle-screen artwork (orca wordmark, payment marks, yellow arrow) from the
reference photo images/orca_logo.jpg.

Writes:
  firmware/components/display/assets/orca_splash.rgb565  raw little-endian RGB565 (embedded)
  firmware/components/display/assets/orca_splash.h        dimensions
  images/generated/orca_splash_preview.png                what it looks like

Run: tools/hil/.venv/bin/python tools/assets/make_splash.py
"""
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "images" / "orca_logo.jpg"
OUT = ROOT / "firmware" / "components" / "display" / "assets"
PREVIEW = ROOT / "images" / "generated"

CROP = (960, 1200, 2110, 2160)  # logo + payment marks + arrow, in the 3154x4678 photo
HEIGHT = 400                    # fits under the 40 px status bar on the 480 px tall panel
BLACK_BELOW = 62                # photo's screen background is ~35-45 luminance; JPEG noise above it
SOFT_RANGE = 34                 # fade to black over this many luminance steps, keeps edges smooth


def clean(px):
    r, g, b = px
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    if lum <= BLACK_BELOW:
        return (0, 0, 0)
    if lum < BLACK_BELOW + SOFT_RANGE:
        k = (lum - BLACK_BELOW) / SOFT_RANGE
        return (int(r * k), int(g * k), int(b * k))
    return px


def main():
    img = Image.open(SRC).convert("RGB").crop(CROP)
    img = img.resize((round(img.width * HEIGHT / img.height), HEIGHT), Image.LANCZOS)
    raw = img.tobytes()
    pixels = [clean(tuple(raw[i:i + 3])) for i in range(0, len(raw), 3)]
    img = Image.frombytes("RGB", img.size, bytes(c for p in pixels for c in p))

    OUT.mkdir(parents=True, exist_ok=True)
    PREVIEW.mkdir(parents=True, exist_ok=True)
    img.save(PREVIEW / "orca_splash_preview.png")

    data = bytearray()
    raw = img.tobytes()
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))
    (OUT / "orca_splash.rgb565").write_bytes(data)
    (OUT / "orca_splash.h").write_text(
        "// Generated by tools/assets/make_splash.py. Do not edit.\n#pragma once\n"
        f"#define ORCA_SPLASH_W {img.width}\n#define ORCA_SPLASH_H {img.height}\n")
    print(f"{img.width}x{img.height}, {len(data) // 1024} KB")


if __name__ == "__main__":
    main()
